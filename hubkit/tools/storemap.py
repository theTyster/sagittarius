#!/usr/bin/env python3
"""storemap.py: make the store map of HUB-CORE.md "What lives where" from hubkit/tools/store-facts.json.

usage: python3 storemap.py [--hub-core FILE] --write | --check
       python3 storemap.py --export DESIGN_KB_DIR      rewrite store-facts.json from the hub design KB
--write replaces the text between the store-map markers; --check exits 1 when it would change.
The facts (stores, fact kinds, owners, cells, descriptions) come from the hub design KB
(eff_fact/2, eff_cell/3, fact_desc/2) through export-store-facts.pl. The columns that say where a
store lives in the hub and which command uses it are written below: they are the hub's own.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FACTS = os.path.join(HERE, "store-facts.json")
CORE = os.path.join(os.path.dirname(HERE), "hub", "HUB-CORE.md")
BEGIN = "<!-- store-map:begin (generated by hubkit/tools/storemap.py) -->"
END = "<!-- store-map:end -->"

# store -> (where it lives in the hub, the command or help topic that uses it)
HOME = {
    "spec": ("`specs/<slug>/` at the hub root, one per ticket",
             "`orbit-kb help core`, `orbit-kb help build`; `hubflow.py where <slug>`"),
    "project": ("the project KB, a directory of its own that the hub's `CLAUDE.md` names",
                "`orbit-kb help project`; `orbit-kb pin-item`"),
    "ledger": ("`flow/flow.db`, with its JSONL in `flow/jsonl/`",
               "`hubflow.py`; skill `hub-flow`"),
    "memory": ("the root files `CLAUDE.md`, `HUB-CORE.md`, `HEURISTICS.md`, `TECHNOLOGIES.md`",
               "read at boot; promote into them at rotation (skill `hub-rotate`)"),
    "weeks": ("`W0/` to `W5/`: `reports/`, `transcripts/`, `outbound-staging/`",
              "`hubflow.py index-transcripts`; skill `hub-rotate`"),
    "bespoke": ("a tool or skill, listed in `TECHNOLOGIES.md` (or the memory file the hub names)",
                "the tool's own help; skill `hub-rotate` prunes the unused"),
    "tracker": ("outside the hub: a pointer such as `issue:123` in a ledger ref",
                "`hubflow.py add --ref`; `orbit-kb pin-item`; `orbit-kb draft`"),
}


def cell(names):
    return ", ".join(f"`{n}`" for n in names) or "-"


def render(facts):
    out = [BEGIN, "", "| Store | Owns | Lives in the hub | Used with |", "|---|---|---|---|"]
    for s in facts["stores"]:
        where, cmd = HOME[s["name"]]
        out.append(f"| `{s['name']}` | {s['owns']} | {where} | {cmd} |")
    out += ["", f"The {len(facts['facts'])} fact kinds:", "",
            "| Fact kind | What it is | Owner | Pinned in | Read from | Copied in |", "|---|---|---|---|---|---|"]
    for f in facts["facts"]:
        out.append(f"| `{f['name']}` | {f['desc']} | `{f['owner']}` | {cell(f['pinned'])} | {cell(f['read'])} | {cell(f['copied'])} |")
    out += ["", END]
    return "\n".join(out)


def apply(text, facts):
    a, b = text.index(BEGIN), text.index(END) + len(END)
    return text[:a] + render(facts) + text[b:]


def main(argv):
    core = CORE
    if "--hub-core" in argv:
        core = argv[argv.index("--hub-core") + 1]
    if "--export" in argv:
        d = argv[argv.index("--export") + 1]
        exp = os.path.join(HERE, "export-store-facts.pl")
        p = subprocess.run(["swipl", "-g", f"consult(load),consult('{exp}'),export_store_facts('{FACTS}'),halt", "-t", "halt"],
                           cwd=d, capture_output=True, text=True)
        sys.stderr.write(p.stderr)
        return p.returncode
    facts = json.load(open(FACTS, encoding="utf-8"))
    text = open(core, encoding="utf-8").read()
    new = apply(text, facts)
    if "--check" in argv:
        if new != text:
            print("storemap: HUB-CORE.md differs from store-facts.json; run storemap.py --write", file=sys.stderr)
            return 1
        return 0
    if "--write" in argv:
        open(core, "w", encoding="utf-8").write(new)
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
