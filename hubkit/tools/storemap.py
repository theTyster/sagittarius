#!/usr/bin/env python3
"""storemap.py: make the store maps of HUB-CORE.md from hubkit/tools/store-facts.json: "What lives where"
and the informal store map (where the informal edition keeps each fact kind, or "not kept"). The
informal map is one table: the same text in hub/HUB-CORE.md ("Without orbit-kb") and in the informal
edition's editions/informal/HUB-CORE.md.

usage: python3 storemap.py [--hub-core FILE] --write | --check
       python3 storemap.py --export DESIGN_KB_DIR      rewrite store-facts.json from the hub design KB
--write replaces the text between the store-map markers and between the informal-map markers of both
HUB-CORE files (or of --hub-core FILE only); --check exits 1 when any would change.
The facts (stores, fact kinds, owners, cells, descriptions) come from the hub design KB
(eff_fact/2, eff_cell/3, fact_desc/2) through export-store-facts.pl. The columns that say where a
store lives in the hub and which command uses it are written below: they are the hub's own. A command
of orbit-kb names the hub's own copy, .claude/orbit-kb/bin/orbit-kb (install UX c3), never a bare orbit-kb.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FACTS = os.path.join(HERE, "store-facts.json")
CORE = os.path.join(os.path.dirname(HERE), "hub", "HUB-CORE.md")
BEGIN = "<!-- store-map:begin (generated by storemap.py of the Sagittarius checkout) -->"
END = "<!-- store-map:end -->"
IBEGIN = "<!-- informal-map:begin (generated by storemap.py of the Sagittarius checkout) -->"
IEND = "<!-- informal-map:end -->"

# store -> (where it lives in the hub, the command or help topic that uses it)
HOME = {
    "spec": ("`specs/<slug>/` at the hub root, one per ticket",
             "`.claude/orbit-kb/bin/orbit-kb help core`, `.claude/orbit-kb/bin/orbit-kb help build`; `hubflow.py where <slug>`"),
    "project": ("the project KB, a directory of its own that the hub's `CLAUDE.md` names",
                "`.claude/orbit-kb/bin/orbit-kb help project`; `.claude/orbit-kb/bin/orbit-kb pin-item`"),
    "ledger": ("`flow/flow.db`, with its JSONL in `flow/jsonl/`",
               "`hubflow.py`; skill `hub-flow`"),
    "memory": ("the root files `CLAUDE.md`, `HUB-CORE.md`, `HEURISTICS.md`, `TECHNOLOGIES.md`",
               "read at boot; promote into them at rotation (skill `hub-rotate`)"),
    "weeks": ("`W0/` to `W5/`: `reports/`, `transcripts/`, `outbound-staging/`",
              "`hubflow.py index-transcripts`; skill `hub-rotate`"),
    "bespoke": ("a tool or skill, listed in `TECHNOLOGIES.md` (or the memory file the hub names)",
                "the tool's own help; skill `hub-rotate` prunes the unused"),
    "tracker": ("outside the hub: a pointer such as `issue:123` in a ledger ref",
                "`hubflow.py add --ref`; `.claude/orbit-kb/bin/orbit-kb pin-item`; `.claude/orbit-kb/bin/orbit-kb draft`"),
}

# The informal store map (T24, T32): every fact kind -> (its informal home, how it is kept there). The
# home is one of the five informal stores, or "not kept". A fact kind that an informal store owns stays
# with that store; the ones that a formal store (or a home outside the hub) owns move or are not kept.
# A fact kind of the design with no entry here makes render_informal fail, so a new fact kind gets a
# home before the map is written. The text is loaded by an informal hub: it names no formal tool.
INFORMAL = {
    "analyses_only": ("weeks", "Reasoning written up about the product or the work: a report in `W0/reports/`. What lasts is promoted into a memory file (`HEURISTICS.md`) at rotation; the rest ages out with its week."),
    "asks": ("ledger", "A question or request that waits on a person: `hubflow.py add ask --waits-on P`; `view waiting_on` lists them."),
    "backlog": ("tracker", "Bugs and feature requests stay in the tracker; the ledger holds a pointer (`issue:123`) to the ones in play."),
    "blocking": ("ledger", "What stops a ticket: an open ask (`add ask --waits-on`) or thread with the ticket's `issue:` ref. `view open` lists what blocks."),
    "boot": ("memory", "What every session loads at start: `CLAUDE.md` and the files it imports."),
    "capsules": ("ledger", "Context for a later session: `hubflow.py capsule ID --summary T`; `show ID` prints it first."),
    "checks": ("tracker", "The tests of each acceptance criterion and their runs: in the tracker item (or the CI it links), next to the criteria."),
    "claims": ("tracker", "The ticket's acceptance criteria, each with an example, in the tracker item. The ticket's ledger thread points to it with its `issue:` ref."),
    "decisions": ("memory", "A decisions file such as `DECISIONS.md`, imported by `CLAUDE.md`: one line per decision, with who decided and when."),
    "designs": ("tracker", "Design documents stay where they live; the ledger holds a pointer (`url:` or `file:` ref) on the item that needs one."),
    "divergences": ("not kept", "No record. The agent says each guess, error and disagreement in its report to the human; one that waits on the human becomes an ask."),
    "handoffs": ("ledger", "Work passed to another session: `hubflow.py handoff --to S`, then `accept ID` by the receiver."),
    "heuristics": ("memory", "Rules of thumb learned here: `HEURISTICS.md`, promoted at rotation."),
    "hypothesis": ("ledger", "A note on the ticket's thread (`hubflow.py note ID TEXT`): what the problem is believed to be, its premises beside it, the result expected, and the result that would show it false."),
    "models": ("bespoke", "A model that a tool or a test of this hub encodes stays with that tool, listed in `TECHNOLOGIES.md`."),
    "outbound": ("weeks", "Text for the tracker or for people, drafted in `W0/outbound-staging/`. A human sends."),
    "product_rules": ("memory", "In the decisions file, or a root file such as `PRODUCT.md` that `CLAUDE.md` imports."),
    "raw_reports": ("weeks", "Raw reports in `W*/reports/` and meeting transcripts in `W*/transcripts/`; an agent that reads a transcript records what is needed in the ledger with a `transcript:` ref (`hubflow.py transcripts --files`)."),
    "repos": ("memory", "The \"Repos\" section of the hub's `CLAUDE.md`."),
    "request": ("tracker", "The ticket's request and the human's answers, in the tracker item. The ledger holds its pointer."),
    "routing": ("ledger", "Who owns each item, who it waits on, links and holds: `--owner`, `--waits-on`, `link`, `park`."),
    "sessions": ("bespoke", "The named sessions and how each starts: a tool set up outside the hub (for example in dotfiles). The hub knows only their names (`flow/seed.json`); `CLAUDE.md` says what each owns."),
    "sop": ("not kept", "How the team works is owned outside the hub; the build does not need it."),
    "tech": ("memory", "The technologies and how to use them here: `TECHNOLOGIES.md`."),
    "ticket_body": ("tracker", "The ticket's text and state stay in the tracker; the ledger holds the pointer, never a copy."),
    "ticket_capsules": ("ledger", "A short summary of an old ticket's history: a capsule on its item (`hubflow.py capsule`)."),
    "ticket_events": ("tracker", "What happened to a ticket and when stays in the tracker; never copied into a capsule."),
    "triage": ("ledger", "The decision for each due item at rotation: `hubflow.py triage ID keep|lapse|capsule|escalate --note T`."),
    "world": ("tracker", "How the current system behaves: the code, git and the tracker; a note names where it was seen."),
}
INFORMAL_STORES = ("ledger", "memory", "weeks", "bespoke", "tracker")
ICORE = os.path.join(os.path.dirname(HERE), "editions", "informal", "HUB-CORE.md")


def cell(names):
    return ", ".join(f"`{n}`" for n in names) or "-"


def render(facts):
    out = [BEGIN, "", "| Store | Owns | Lives in the hub | Used with |", "|---|---|---|---|"]
    for s in facts["stores"]:
        where, cmd = HOME[s["name"]]
        out.append(f"| `{s['name']}` | {s['owns']} | {where} | {cmd} |")
    out += ["", f"The {len(facts['facts'])} fact kinds:", "",
            "| Fact kind | What it is | Owner | Pinned in | Read from | Copied in |", "|---|---|---|---|---|---|"]
    for f in facts["facts"]:
        out.append(f"| `{f['name']}` | {f['desc']} | `{f['owner']}` | {cell(f['pinned'])} | {cell(f['read'])} | {cell(f['copied'])} |")
    out += ["", END]
    return "\n".join(out)


def render_informal(facts):
    out = [IBEGIN, "", "| Fact kind | Informal home | How |", "|---|---|---|"]
    for f in facts["facts"]:
        home, how = INFORMAL[f["name"]]
        if f["owner"] in INFORMAL_STORES and home != f["owner"]:
            raise SystemExit(f"storemap: {f['name']} is owned by {f['owner']}, an informal store; its informal home must be {f['owner']}")
        if home not in INFORMAL_STORES + ("not kept",):
            raise SystemExit(f"storemap: {f['name']}: {home} is not an informal store")
        out.append(f"| `{f['name']}` | `{home}` | {how} |")
    out += ["", IEND]
    return "\n".join(out)


def apply(text, facts):
    for begin, end, fn in ((BEGIN, END, render), (IBEGIN, IEND, render_informal)):
        if begin in text:
            a, b = text.index(begin), text.index(end) + len(end)
            text = text[:a] + fn(facts) + text[b:]
    return text


def main(argv):
    core = CORE
    if "--hub-core" in argv:
        core = argv[argv.index("--hub-core") + 1]
    if "--export" in argv:
        d = argv[argv.index("--export") + 1]
        exp = os.path.join(HERE, "export-store-facts.pl")
        p = subprocess.run(["swipl", "-g", f"consult(load),consult('{exp}'),export_store_facts('{FACTS}'),halt", "-t", "halt"],
                           cwd=d, capture_output=True, text=True)
        sys.stderr.write(p.stderr)
        return p.returncode
    facts = json.load(open(FACTS, encoding="utf-8"))
    cores = [core] if "--hub-core" in argv else [CORE, ICORE]
    stale = []
    for c in cores:
        text = open(c, encoding="utf-8").read()
        new = apply(text, facts)
        if new != text:
            stale.append(c)
            if "--write" in argv:
                open(c, "w", encoding="utf-8").write(new)
    if "--check" in argv:
        if stale:
            print("storemap: differs from store-facts.json: " + ", ".join(stale) + "; run storemap.py --write", file=sys.stderr)
            return 1
        return 0
    if "--write" in argv:
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
